import { Question, ClassLevel } from '../types';

/**
 * Diagnostic Assessment Questions specifically testing PREVIOUS CLASS KNOWLEDGE
 * 
 * When a student in Class 10 takes the assessment, it diagnostic-tests their
 * Class 9 foundational concepts across Mathematics, Science, English, and Social Science.
 * 
 * Similarly:
 * - Class 9 students are tested on Class 8 prerequisite concepts
 * - Class 8 students are tested on Class 7 prerequisite concepts
 * - Class 7 students are tested on Class 6 prerequisite concepts
 * - Class 11 students are tested on Class 10 prerequisite concepts
 */

export function getPreviousClass(currentClass: ClassLevel): ClassLevel {
  switch (currentClass) {
    case 'Class 12': return 'Class 11';
    case 'Class 11': return 'Class 10';
    case 'Class 10': return 'Class 9';
    case 'Class 9': return 'Class 8';
    case 'Class 8': return 'Class 7';
    case 'Class 7': return 'Class 6';
    case 'Class 6': return 'Class 5';
    case 'Class 5': return 'Class 4';
    case 'Class 4': return 'Class 3';
    case 'Class 3': return 'Class 2';
    case 'Class 2': return 'Class 1';
    default: return 'Class 9';
  }
}

