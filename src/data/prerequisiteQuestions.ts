/**
 * Helper to fetch prerequisite diagnostic questions for a student's enrolled class.
 * Ensures the questions test the foundational knowledge of the PREVIOUS class.
 */
export function getPrerequisiteQuestionsForClass(
  enrolledClass: ClassLevel,
  selectedSubjectIds?: string[],
  count: number = 20
): Question[] {
  const previousClass = getPreviousClass(enrolledClass);
  
  // Filter questions that test previous class knowledge for the current class
  let pool = PREREQUISITE_QUESTIONS.filter(
    (q) => q.class === enrolledClass || q.prerequisiteClass === previousClass
  );

  // If specific subjects are requested, filter by subject
  if (selectedSubjectIds && selectedSubjectIds.length > 0) {
    const subjectFiltered = pool.filter((q) =>
      selectedSubjectIds.includes(q.subjectId) ||
      selectedSubjectIds.some(subId => q.subjectId.includes(subId.replace('sub_c10_', '').replace('sub_', '')))
    );
    if (subjectFiltered.length >= 4) {
      pool = subjectFiltered;
    }
  }

  // If we have enough prerequisite questions, return up to count
  if (pool.length >= count) {
    return pool.slice(0, count);
  }

  return pool;
}
